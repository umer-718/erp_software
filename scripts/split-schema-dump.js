// Splits a pg_dump schema file into:
//   sql/central/001_schema.sql  - auth/company tables (erp_system)
//   sql/tenant/001_schema.sql   - operational tables (each erp_<company name>)
// Foreign keys from tenant tables to central tables are dropped, because
// PostgreSQL cannot enforce them across databases.
//
// Usage: node scripts/split-schema-dump.js [dump.sql]
// (default: erp_system_current_schema.sql). Run once; commit the output.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";
import { CENTRAL_TABLES } from "../lib/tenant-tables.js";

const source = process.argv[2] || "erp_system_current_schema.sql";
const dump = readFileSync(source, "utf8");
const central = new Set(CENTRAL_TABLES);

// pg_dump separates objects with "--\n-- Name: ...; Type: ...;" headers.
const blocks = dump.split(/\n(?=--\n-- Name: )/).slice(1);

const tableOf = (block, type) => {
  const sql = block.replace(/^--[^\n]*\n/gm, "");
  let m;
  if (type === "TABLE") m = sql.match(/CREATE TABLE public\.([a-z0-9_]+)/);
  else if (type === "SEQUENCE OWNED BY") m = sql.match(/OWNED BY public\.([a-z0-9_]+)\./);
  else if (type === "INDEX") m = sql.match(/ ON (?:ONLY )?public\.([a-z0-9_]+)/);
  else if (type === "SEQUENCE") {
    // Identity columns: "ALTER TABLE ... ADD GENERATED ... AS IDENTITY".
    m = sql.match(/ALTER TABLE (?:ONLY )?public\.([a-z0-9_]+)/);
    if (!m) return null; // plain sequence: decided via OWNED BY below
  }
  else m = sql.match(/ALTER TABLE (?:ONLY )?public\.([a-z0-9_]+)/);
  return m ? m[1] : null;
};

// Map sequences to their owning table.
const sequenceTable = new Map();
for (const block of blocks) {
  const m = block.match(/ALTER SEQUENCE public\.([a-z0-9_]+) OWNED BY public\.([a-z0-9_]+)\./);
  if (m) sequenceTable.set(m[1], m[2]);
}

const out = { central: [], tenant: [] };
let droppedFks = 0;

for (const block of blocks) {
  const type = (block.match(/^--\n-- Name: [^;]*; Type: ([A-Z ]+);/) || [])[1]?.trim();
  if (!type || type === "EXTENSION" || type === "COMMENT" || type === "SCHEMA") continue;

  let table = tableOf(block, type);
  if (type === "SEQUENCE" && !table) {
    const seq = (block.match(/CREATE SEQUENCE public\.([a-z0-9_]+)/) || [])[1];
    table = sequenceTable.get(seq) || null;
  }
  if (!table) {
    // Standalone sequences (e.g. *_number_seq) are only used by tenant tables.
    console.info(`Standalone ${type} -> tenant:`, block.split("\n")[1].replace("-- Name: ", ""));
  }

  const isCentral = table && central.has(table);

  if (type === "FK CONSTRAINT" && !isCentral) {
    const target = (block.match(/REFERENCES public\.([a-z0-9_]+)/) || [])[1];
    if (target && central.has(target)) {
      droppedFks += 1;
      continue;
    }
  }

  (isCentral ? out.central : out.tenant).push(block.trim());
}

const clean = (text) =>
  text
    .replace(/^\\(un)?restrict .*$/gm, "")
    .replace(/^-- PostgreSQL database dump complete\s*$/gm, "")
    .trim();

const header = (what) => `-- ${what}
-- GENERATED by scripts/split-schema-dump.js from ${path.basename(source)}.
-- Do not edit; add a new numbered migration file for later changes.

SET check_function_bodies = false;
SET client_min_messages = warning;
`;

const write = (file, what, parts) => {
  mkdirSync(path.dirname(file), { recursive: true });
  writeFileSync(file, `${header(what)}\n${clean(parts.join("\n\n"))}\n`);
  const tables = parts.filter((p) => /CREATE TABLE /.test(p)).length;
  console.info(`Wrote ${file}: ${tables} tables, ${parts.length} objects.`);
};

write("sql/central/001_schema.sql", "Central (erp_system) schema.", out.central);
write("sql/tenant/001_schema.sql", "Tenant (per-company) schema.", out.tenant);
console.info(`Dropped ${droppedFks} cross-database foreign keys.`);
